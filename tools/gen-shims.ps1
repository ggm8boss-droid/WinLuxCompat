# Regenerates bin\*.cmd, the cmd.exe side of linux-compat. Run after adding a command to lib\*.ps1:
#   powershell -NoProfile -ExecutionPolicy Bypass -File tools\gen-shims.ps1
$ErrorActionPreference = 'Stop'
$root = Split-Path -Parent $PSScriptRoot
. (Join-Path $root 'linux-compat.ps1') -NonInteractive
$bin = Join-Path $root 'bin'
# Names that are also Windows programs (find, sort, timeout) must not be found on PATH: a .bat that runs
# `sort /r` would jump into our .cmd and never come back. They live in cmd\shadow, reached by doskey
# macros (typed commands only), plus g-prefixed copies in bin (gsort, gfind, gtimeout) for pipes/scripts.
$shadow = Join-Path $root 'cmd\shadow'
foreach ($d in $bin, $shadow) {
    if (Test-Path $d) { Get-ChildItem $d -Filter *.cmd | Remove-Item } else { [void](New-Item -ItemType Directory $d) }
}

$runner = '"%SystemRoot%\System32\WindowsPowerShell\v1.0\powershell.exe" -NoLogo -NoProfile -ExecutionPolicy Bypass -File "%~dp0..\lib\run.ps1"'
$enc = New-Object Text.UTF8Encoding $false
function Out-Shim([string]$name, [string]$text, [string]$dir = $bin) { [IO.File]::WriteAllText((Join-Path $dir "$name.cmd"), ($text -replace "`r?`n", "`r`n"), $enc) }

# Commands whose Windows program shares the name: Windows-style args go to Windows.
$winCheck = @{
    find    = 'if "%~1"=="" goto gnu' + "`n" + 'if [%1]==["%~1"] goto win' + "`n" + 'set "_lc1=%~1"' + "`n" + 'if "%_lc1:~0,1%"=="/" goto win'
    sort    = 'set "_lc1=%~1"' + "`n" + 'if "%_lc1:~0,1%"=="/" goto win'
    timeout = 'set "_lc1=%~1"' + "`n" + 'if "%_lc1:~0,1%"=="/" goto win' + "`n" + 'if "%~2"=="" goto win'
}

# GNU-first commands: run the GNU exe directly (fast), else the PowerShell fallback.
$gnu = @($global:LC_GNU_CMDS.Keys) + @('timeout')
foreach ($n in $gnu) {
    $spec = if ($global:LC_GNU_CMDS.Contains($n)) { "$($global:LC_GNU_CMDS[$n])" } else { '' }
    $exe = $n; $pre = ''
    if ($spec) { $parts = $spec -split ' '; $exe = $parts[0]; $pre = (@($parts | Select-Object -Skip 1) -join ' ') }
    $fa = _lc_gnu_args $n @()
    $fixed = @($fa | ForEach-Object { if ($_ -match '\s') { "`"$_`"" } else { $_ } }) -join ' '
    if ($pre) { $fixed = "$pre $fixed".Trim() }
    $fixed = $fixed -replace '%', '%%'
    $check = if ($winCheck.ContainsKey($n)) { $winCheck[$n] + "`n" } else { '' }
    $win = if ($winCheck.ContainsKey($n)) { ":win`n`"%SystemRoot%\System32\$n.exe`" %*`nexit /b`n" } else { '' }
    $text = @"
@echo off
rem linux-compat: $n (GNU tool if found, else the PowerShell version). Generated by tools\gen-shims.ps1.
setlocal
$($check):gnu
if not defined LC_GNU call "%~dp0..\cmd\gnu.cmd"
if not exist "%LC_GNU%\$exe.exe" goto native
if exist "%~dp0..\state\nognu" goto native
if exist "%~dp0..\state\debug" echo [linux-compat] -^> GNU $exe $pre %* 1>&2
set "PATH=%LC_GNU%;%PATH%"
"%LC_GNU%\$exe.exe" $fixed %*
exit /b
:native
$runner $n %*
exit /b
$win
"@
    if ($winCheck.ContainsKey($n)) {
        Out-Shim $n ($text -replace '%~dp0\.\.\\', '%~dp0..\..\') $shadow
        Out-Shim "g$n" $text
    } else { Out-Shim $n $text }
}

# PowerShell-only commands (system tools, package managers, bash helpers).
$psOnly = @('which', 'env', 'printenv', 'realpath', 'readlink', 'basename', 'dirname', 'mktemp', 'ln', 'man',
    'ps', 'kill', 'killall', 'pkill', 'pgrep', 'pidof', 'free', 'df', 'uname', 'uptime', 'nproc', 'id', 'groups',
    'top', 'htop', 'ip', 'ifconfig', 'ss', 'lsof', 'lsblk', 'lscpu', 'lsusb', 'lspci', 'journalctl', 'dmesg',
    'systemctl', 'service', 'hostnamectl', 'timedatectl', 'lsb_release', 'xdg-open', 'open', 'gio', 'xclip', 'xsel',
    'wl-copy', 'wl-paste', 'wget', 'watch', 'poweroff', 'halt', 'reboot', 'traceroute', 'dig',
    'apt', 'apt-get', 'apt-cache', 'dpkg', 'yum', 'dnf', 'zypper', 'apk', 'snap', 'flatpak', 'pacman', 'brew', 'linuxcompat')
foreach ($n in $psOnly) {
    if (-not (Get-Command $n -CommandType Function -ErrorAction SilentlyContinue)) { throw "no PowerShell function for $n" }
    Out-Shim $n "@rem linux-compat: $n (PowerShell version). Generated by tools\gen-shims.ps1.`n@$runner $n %*`n"
}

# Batch builtins that change this cmd session (export, cd helpers, alias...).
Get-ChildItem (Join-Path $root 'cmd\builtins') -Filter *.cmd | ForEach-Object { Copy-Item $_.FullName (Join-Path $bin $_.Name) }

"$(@(Get-ChildItem $bin -Filter *.cmd).Count) shims in $bin"
